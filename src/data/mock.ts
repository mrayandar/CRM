/* Dates are generated relative to "now" so the dataset always reads as current. */
const NOW = new Date()

function shift(days: number, hours = 0): string {
  const d = new Date(NOW)
  d.setDate(d.getDate() + days)
  d.setHours(9 + hours, (Math.abs(days) * 13) % 60, 0, 0)
  return d.toISOString()
}

const ago = (days: number, hours = 0) => shift(-days, hours)
const ahead = (days: number, hours = 0) => shift(days, hours)

